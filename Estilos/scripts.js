function cargarIndicadores() {
  const loader = document.getElementById('dashboard-loader');
  const content = document.getElementById('dashboard-content');

  fetch('data/indicadores.json')
    .then(response => {
      if (!response.ok) throw new Error('No se pudo cargar data/indicadores.json');
      return response.json();
    })
    .then(data => {
      cachedIndicadoresData = data;
      // Manejo del estado de carga: ocultar loader y mostrar contenido
      if (loader) loader.style.display = 'none';
      if (content) {
        content.style.display = 'block';
        if (typeof revealObserver !== 'undefined') {
          content.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));
        }
      }

      // Animaciones de conteo para métricas principales
      animarConteo('val-participantes', data.total_participantes || 0);
      animarConteo('val-paises', data.paises_impactados || 0);
      animarConteo('val-capacitaciones', data.capacitaciones_realizadas || 0);

      // Roles de Participantes
      if (data.roles_participantes) {
        animarConteo('val-docentes', data.roles_participantes.docentes || 0);
        animarConteo('val-investigadores', data.roles_participantes.investigadores || 0);
        animarConteo('val-estudiantes', data.roles_participantes.estudiantes || 0);
        animarConteo('val-aliados', data.roles_participantes.aliados_externos || 0);
      }

      // Comunidades Impactadas
      if (data.comunidades_impactadas) {
        animarConteo('val-indigenas', data.comunidades_impactadas.indigenas || 0);
        animarConteo('val-rurales', data.comunidades_impactadas.rurales || 0);
      }

      // Barra de progreso global
      const pctAvance = data.avance_global || 0;
      animarConteo('val-avance', pctAvance, '%');
      const barraAvance = document.getElementById('barra-avance');
      if (barraAvance) {
        setTimeout(() => {
          barraAvance.style.width = `${pctAvance}%`;
        }, 150);
      }

      // Inicializar gráficos condicionales con Intersection Observer
      initChartsWithObserver(data);
    })
    .catch(err => {
      console.error('Error al cargar datos del Dashboard:', err);
      if (loader) {
        const lang = localStorage.getItem('idiomaActivo') || 'es';
        const msgPrincipal = lang === 'en'
          ? 'Could not load real-time indicators.'
          : 'No se pudieron cargar los indicadores en tiempo real.';
        const msgSecundario = lang === 'en'
          ? 'Please verify the existence of <code>data/indicadores.json</code>.'
          : 'Por favor verifica la existencia de <code>data/indicadores.json</code>.';
        loader.innerHTML = `
          <div style="text-align: center; padding: 40px 20px; color: var(--slate);">
            <p style="font-weight: 700; color: var(--purple);">${msgPrincipal}</p>
            <p style="font-size: 13px; margin-top: 8px;">${msgSecundario}</p>
          </div>
        `;
      }
    });
}

/* ── MÓDULO DE TRADUCCIÓN (i18n) ── */
let dictIdiomas = null;

async function cargarDiccionario() {
  try {
    const res = await fetch('data/idiomas.json');
    if (res.ok) {
      dictIdiomas = await res.json();
    }
  } catch (err) {
    console.error('Error cargando diccionario de idiomas:', err);
  }
}

function obtenerValorIdioma(clave, lang) {
  if (!dictIdiomas) return null;
  const partes = clave.split('.');
  if (partes.length === 2) {
    const objeto = dictIdiomas[partes[0]];
    if (objeto) {
      const claveFinal = `${partes[1]}_${lang}`;
      return objeto[claveFinal];
    }
  }
  return null;
}

async function aplicarIdioma(lang) {
  if (!dictIdiomas) {
    await cargarDiccionario();
  }
  const elementos = document.querySelectorAll('[data-i18n]');
  elementos.forEach(el => {
    const clave = el.getAttribute('data-i18n');
    const valor = obtenerValorIdioma(clave, lang);
    if (valor) {
      el.classList.add('fade-out');
      setTimeout(() => {
        el.innerHTML = valor;
        el.classList.remove('fade-out');
      }, 300);
    }
  });

  const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const clave = el.getAttribute('data-i18n-placeholder');
    const valor = obtenerValorIdioma(clave, lang);
    if (valor) {
      el.setAttribute('placeholder', valor);
    }
  });

  const btnIdioma = document.querySelectorAll('.lang-switch');
  btnIdioma.forEach(btn => {
    btn.innerText = lang === 'es' ? 'EN' : 'ES';
  });
  
  document.documentElement.lang = lang;
  localStorage.setItem('idiomaActivo', lang);

  if (activeModalKey) {
    renderModalContent();
  }

  if (cachedIndicadoresData && typeof Chart !== 'undefined') {
    const canvasGenero = document.getElementById('graficoGenero');
    if (canvasGenero && Chart.getChart(canvasGenero)) {
      renderGraficoGenero(canvasGenero, cachedIndicadoresData.distribucion_genero);
    }
    const canvasRoles = document.getElementById('graficoRoles');
    if (canvasRoles && Chart.getChart(canvasRoles)) {
      renderGraficoRoles(canvasRoles, cachedIndicadoresData.roles_participantes);
    }
  }
}

document.addEventListener('DOMContentLoaded', async () => {
  const langGuardado = localStorage.getItem('idiomaActivo') || 'es';
  await aplicarIdioma(langGuardado);

  const btnIdioma = document.querySelectorAll('.lang-switch');
  btnIdioma.forEach(btn => {
    btn.addEventListener('click', () => {
      const actual = localStorage.getItem('idiomaActivo') || 'es';
      const nuevo = actual === 'es' ? 'en' : 'es';
      aplicarIdioma(nuevo);
    });
  });
});