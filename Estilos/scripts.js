/* ── MODAL ── */
let activeModalKey = null;

function renderModalContent() {
  if (!activeModalKey) return;
  const data = modalData[activeModalKey];
  if (!data) return;
  const lang = localStorage.getItem('idiomaActivo') || 'es';
  const title = lang === 'en' ? (data.title_en || data.title_es) : data.title_es;
  const body = lang === 'en' ? (data.body_en || data.body_es) : data.body_es;
  const content = document.getElementById('modal-content');
  if (content) {
    content.innerHTML = `<h2>${title}</h2><div style="margin-top:12px; line-height:1.7; color:var(--slate)">${body}</div>`;
  }
}

function openModal(key) {
  activeModalKey = key;
  renderModalContent();
  const overlay = document.getElementById('modal-overlay');
  if (overlay) overlay.classList.add('active');
}

function closeModal() {
  activeModalKey = null;
  const overlay = document.getElementById('modal-overlay');
  if (overlay) overlay.classList.remove('active');
}
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') closeModal();
});

function filtrar(btn, categoria) {
  document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');

  document.querySelectorAll('#noticias-grid .news-card').forEach(card => {
    const mostrar = categoria === 'todas' || card.dataset.cat === categoria;
    card.style.display = mostrar ? '' : 'none';
  });
}

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      revealObserver.unobserve(entry.target); 
    }
  });
}, { threshold: 0.12 });

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));
});
